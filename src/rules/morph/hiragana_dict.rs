use super::pattern::Expect;
use super::pattern::Field::{self, *};

/// ひらがなで書く語の辞書の1項目
#[derive(Debug)]
pub struct Entry {
    /// 置き換え後の語
    pub expected: &'static str,
    /// 指摘の範囲が始まるトークンの、並びの中の位置。形式名詞の辞書だけが0でない
    pub offset: usize,
    pub pattern: &'static [Expect],
}

/// さ入れ・さ抜きのパターン
#[derive(Debug)]
pub struct SaPattern {
    /// さ入れなら、取り除く `さ` のトークンの並びの中の位置で、指摘の範囲はここから始まる。さ抜きなら無く、
    /// 指摘の範囲は最初のトークンから始まり、置き換え後の語は2つのトークンの間に `さ` を入れたものである
    pub inserted: Option<usize>,
    pub pattern: &'static [Expect],
}

const fn expect(fields: &'static [(Field, &'static [&'static str])]) -> Expect {
    Expect {
        fields,
        skippable: false,
    }
}

